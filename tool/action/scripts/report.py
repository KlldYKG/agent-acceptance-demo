#!/usr/bin/env python3
"""Render the PR comment (report.md) from evidence.json. Deterministic projection."""
import json
import sys
from pathlib import Path

ICONS = {"passed": "✅", "failed": "❌", "error": "💥", "missing": "❔"}
VERDICT_ICON = {"VALID": "**VALID** ✅", "PRE-PASS": "PRE-PASS ⚠️", "BROKEN": "BROKEN ✗",
                "ERROR": "ERROR 💥"}
MARKER = "<!-- agent-acceptance:report -->"


def main() -> None:
    out = Path(sys.argv[1])
    ev = json.loads((out / "evidence.json").read_text())
    c, mut = ev["counts"], ev["mutation"]

    if ev["verdict"] == "NO_EVIDENCE":
        (out / "report.md").write_text(
            f"{MARKER}\n## 🧪 Test-evidence assessment — non-blocking\n\n"
            "No test files were changed in this PR, so there is no executable "
            "test evidence to verify.\n")
        return

    lines = [
        MARKER,
        "## 🧪 Test-evidence assessment — non-blocking",
        "",
        f"**Strength: {ev['strength']}** · "
        f"{c['VALID']} valid / {c['PRE-PASS']} pre-pass / {c['BROKEN']} broken / "
        f"{c['ERROR']} error · base `{ev['base_sha'][:7]}` → head `{ev['head_sha'][:7]}`"
        " · sandbox: no-network, 2 CPU / 2 GB, read-only FS",
        "",
        "| Changed test | on base | on PR | verdict |",
        "|---|---|---|---|",
    ]
    for r in ev["tests"]:
        lines.append(
            f"| `{r['test']}` | {ICONS.get(r['on_base'], r['on_base'])} | "
            f"{ICONS.get(r['on_pr'], r['on_pr'])} | {VERDICT_ICON[r['verdict']]} |")

    lines += ["", "**Mutation sampling** (mutmut, time-budgeted):"]
    if mut["status"] != "OK" or mut["score"] is None:
        lines.append(f"- *SKIPPED ({mut['status'].lower()})* — no mutation numbers reported.")
    else:
        lines.append(f"- score **{mut['killed']}/{mut['killed'] + mut['survived']} "
                     f"({round(100 * mut['score'])}%)** — mutants killed by the changed tests")
        for s in mut["survivor_samples"]:
            lines.append(f"  - `{s['mutant']}` — {s['detail']}")

    lines += [
        "",
        "<sub>Report mode: this comment does not block merge. "
        "VALID = failed on base, passed on PR (real evidence) · "
        "PRE-PASS = test already passed on base (proves nothing about the change) · "
        "BROKEN = test fails on both (test itself is broken) · "
        "surviving mutants = behaviors your tests do not pin down. "
        "Generated by agent-acceptance — deterministic execution, no LLM involved.</sub>",
    ]
    (out / "report.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
